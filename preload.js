const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  openFile: () => ipcRenderer.invoke('open-file'),
  saveFile: (payload) => ipcRenderer.invoke('save-file', payload),
  pickImage: () => ipcRenderer.invoke('pick-image'),
  exportPdf: (name) => ipcRenderer.invoke('export-pdf', name),
  print: () => ipcRenderer.invoke('print'),
  setTitle: (t) => ipcRenderer.send('set-title', t),
  setDirty: (d) => ipcRenderer.send('set-dirty', d),
  onMenu: (cb) => ipcRenderer.on('menu', (_e, cmd) => cb(cmd)),
  edit: (cmd) => ipcRenderer.send('edit', cmd),
  docxBasic: (bytes) => ipcRenderer.invoke('docx-basic', bytes),
  listFonts: () => ipcRenderer.invoke('list-fonts'),
  contextInfo: (info) => ipcRenderer.sendSync('context-info', info),
  openPath: (p) => ipcRenderer.invoke('open-path', p),
  pathForFile: (f) => webUtils.getPathForFile(f),
  fetchImage: (url) => ipcRenderer.invoke('fetch-image', url),
  appVersion: () => ipcRenderer.invoke('app-version'),
  onUpdate: (cb) => ipcRenderer.on('update-status', (_e, info) => cb(info)),
  checkForUpdates: () => ipcRenderer.send('update-check'),
  downloadUpdate: () => ipcRenderer.send('update-download'),
  installUpdate: () => ipcRenderer.send('update-install'),
  recoverySave: (data) => ipcRenderer.invoke('recovery-save', data),
  recoveryClear: () => ipcRenderer.invoke('recovery-clear'),
  recoveryList: () => ipcRenderer.invoke('recovery-list'),
  recoveryLoad: (id) => ipcRenderer.invoke('recovery-load', id),
  recoveryDelete: (id) => ipcRenderer.invoke('recovery-delete', id),
  recentList: () => ipcRenderer.invoke('recent-list'),
  closeNow: () => ipcRenderer.send('close-now'),
  onOpenPath: (cb) => ipcRenderer.on('open-path-result', (_e, r) => cb(r)),
});
