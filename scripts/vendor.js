// Copies third-party browser files into src/ so the app works offline.
//   - docx-preview + JSZip (high-fidelity .docx reader)
//   - bundled free fonts from @fontsource (Latin + Latin Extended, regular/bold/italic)
// Run: node scripts/vendor.js   (output is committed, so builds don't need it)
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const nm = (...p) => path.join(root, 'node_modules', ...p);
const out = (...p) => path.join(root, 'src', ...p);

fs.mkdirSync(out('vendor'), { recursive: true });
fs.copyFileSync(nm('jszip', 'dist', 'jszip.min.js'), out('vendor', 'jszip.min.js'));
fs.copyFileSync(nm('docx-preview', 'dist', 'docx-preview.min.js'), out('vendor', 'docx-preview.min.js'));

const FONTS = [
  'roboto', 'open-sans', 'lato', 'montserrat', 'poppins', 'inter', 'raleway', 'nunito', 'oswald',
  'work-sans', 'quicksand', 'noto-sans', 'source-sans-3', 'ubuntu', 'carlito',
  'merriweather', 'playfair-display', 'lora', 'noto-serif', 'pt-serif', 'source-serif-4',
  'eb-garamond', 'libre-baskerville', 'crimson-text', 'caladea',
  'dancing-script', 'pacifico', 'caveat', 'roboto-mono', 'fira-code',
];
// Metric-compatible stand-ins so Word documents keep their layout on PCs without Office fonts.
const ALIASES = { carlito: 'Calibri', caladea: 'Cambria' };

fs.rmSync(out('fonts'), { recursive: true, force: true });
fs.mkdirSync(out('fonts', 'files'), { recursive: true });
let css = '/* Generated by scripts/vendor.js. Fonts are licensed under OFL-1.1 / Apache-2.0, see LICENSES.txt */\n';
let licenses = '';
const list = [];

for (const id of FONTS) {
  const dir = nm('@fontsource', id);
  const meta = JSON.parse(fs.readFileSync(path.join(dir, 'metadata.json'), 'utf8'));
  const weights = [400, 700].filter((w) => meta.weights.includes(w));
  if (!weights.length) weights.push(meta.weights.includes(500) ? 500 : meta.weights[0]);
  const styles = meta.styles.includes('italic') ? ['normal', 'italic'] : ['normal'];
  for (const w of weights) {
    for (const st of styles) {
      const file = path.join(dir, `${w}${st === 'italic' ? '-italic' : ''}.css`);
      if (!fs.existsSync(file)) continue;
      const src = fs.readFileSync(file, 'utf8');
      const blocks = src.split(/(?=\/\*)/).filter((b) => /-latin(-ext)?-\d+-/.test(b.split('\n')[0]));
      for (const b of blocks) {
        const woff2 = b.match(/url\(\.\/files\/([^)]+\.woff2)\)/)[1];
        fs.copyFileSync(path.join(dir, 'files', woff2), out('fonts', 'files', woff2));
        const range = (b.match(/unicode-range:[^;]+;/) || [''])[0];
        const face = (family, local) => `@font-face{font-family:'${family}';font-style:${st};font-weight:${w};font-display:swap;src:${local ? `local('${local}'),` : ''}url(files/${woff2}) format('woff2');${range}}\n`;
        css += face(meta.family);
        if (ALIASES[id]) css += face(ALIASES[id], ALIASES[id] + (w === 700 ? ' Bold' : '') + (st === 'italic' ? ' Italic' : ''));
      }
    }
  }
  list.push({ family: meta.family, category: meta.category });
  const lic = path.join(dir, 'LICENSE');
  licenses += `==== ${meta.family} (${meta.license.type}) ====\n${meta.license.attribution || ''}\n\n${fs.existsSync(lic) ? fs.readFileSync(lic, 'utf8') : ''}\n\n`;
}
fs.writeFileSync(out('fonts', 'fonts.css'), css);
fs.writeFileSync(out('fonts', 'LICENSES.txt'), licenses);
fs.writeFileSync(out('fonts', 'bundled.js'), `// Generated by scripts/vendor.js\nwindow.BUNDLED_FONTS = ${JSON.stringify(list, null, 1)};\n`);
console.log(`vendored ${list.length} fonts, ${fs.readdirSync(out('fonts', 'files')).length} files`);
